using Content.Client.Computer;
using Content.Client.UserInterface.Controls;
using Content.Shared.Shuttles.BUIStates;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Floof.MapLayer.Transit;

[GenerateTypedNameReferences]
public sealed partial class SubConsoleWindow : FancyWindow,
    IComputerWindow<ShuttleBoundUserInterfaceState>
{
    [Dependency] private IEntityManager _entManager = default!;

    public event Action? OnSonarToggled;
    public event Action? OnLift;
    public event Action? OnLand;
    public event Action? OnDock;
    public event Action<NetEntity, NetEntity>? DockRequest;
    public event Action<NetEntity>? UndockRequest;

    public SubConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        NavContainer.OnSonarToggled += () => OnSonarToggled?.Invoke();
        DockContainer.OnLift += () => OnLift?.Invoke();
        DockContainer.OnLand += () => OnLand?.Invoke();
        DockContainer.OnDock += () => OnDock?.Invoke();
        DockContainer.DockRequest += (dock, target) => DockRequest?.Invoke(dock, target);
        DockContainer.UndockRequest += dock => UndockRequest?.Invoke(dock);

        var group = new ButtonGroup();
        NavModeButton.Group = group;
        DockModeButton.Group = group;
        NavModeButton.Pressed = true;
        NavModeButton.OnPressed += _ => ShowDock(false);
        DockModeButton.OnPressed += _ => ShowDock(true);
    }

    private void ShowDock(bool dock)
    {
        NavContainer.Visible = !dock;
        DockContainer.Visible = dock;
    }

    public void UpdateState(EntityUid owner, ShuttleBoundUserInterfaceState cState)
    {
        var coordinates = _entManager.GetCoordinates(cState.NavState.Coordinates);
        NavContainer.SetShuttle(coordinates?.EntityId);
        NavContainer.SetConsole(owner);
        NavContainer.UpdateState(cState.NavState);
        DockContainer.UpdateState(coordinates?.EntityId, cState.DockState);
    }
}
