using System.Numerics;
using Content.Client.Shuttles.UI;
using Content.Shared._Floof.MapLayer.Transit;
using Content.Shared.Shuttles.Systems;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Map.Components;

namespace Content.Client._Floof.MapLayer.Transit;

[GenerateTypedNameReferences]
public sealed partial class TransitDockView : BaseShuttleControl
{
    private static readonly Color BelowColor = Color.FromHex("#5a7d9a");
    private static readonly Color GhostColor = Color.Cyan;

    private readonly MapLayerSystem _layers;
    private readonly SharedShuttleSystem _shuttles;
    private readonly SharedTransformSystem _transform;
    private readonly List<(EntityUid Map, float Gap)> _gaps = new();

    public EntityUid? Shuttle;

    public TransitDockView() : base(8f, 28f, 24f)
    {
        RobustXamlLoader.Load(this);
        _layers = EntManager.System<MapLayerSystem>();
        _shuttles = EntManager.System<SharedShuttleSystem>();
        _transform = EntManager.System<SharedTransformSystem>();
    }

    protected override void Draw(DrawingHandleScreen handle)
    {
        base.Draw(handle);

        DrawBacking(handle);

        if (Shuttle is not { } shuttle ||
            !EntManager.TryGetComponent(shuttle, out MapGridComponent? grid) ||
            !EntManager.TryGetComponent(shuttle, out TransformComponent? xform) ||
            xform.MapUid is not { } map)
            return;

        var (_, rotation, gridToWorld) = _transform.GetWorldPositionRotationMatrix(xform);
        var center = Vector2.Transform(grid.LocalAABB.Center, gridToWorld);
        Matrix3x2.Invert(Matrix3Helpers.CreateTransform(center, rotation), out var worldToSub);
        var worldToView = worldToSub *
                          Matrix3x2.CreateScale(MinimapScale, -MinimapScale) *
                          Matrix3x2.CreateTranslation(MidPointVector);

        if (TryGetBelow(map, out var below, out var gap))
        {
            var scale = 1f / MapLayerSystem.GetZoom(gap);
            var belowToView = Matrix3x2.CreateScale(scale, center) * worldToView;
            DrawGridsOn(handle, below, belowToView, BelowColor);

            if (EntManager.TryGetComponent(shuttle, out TransitDockPreviewComponent? preview))
            {
                var ghostToView = Matrix3Helpers.CreateTransform(preview.Position, preview.Rotation) * belowToView;
                DrawGrid(handle, ghostToView, (shuttle, grid), GhostColor, 0.05f);
            }
        }

        DrawGridsOn(handle, map, worldToView, null, shuttle);
        DrawGrid(handle, gridToWorld * worldToView, (shuttle, grid), _shuttles.GetIFFColor(shuttle, self: true));
    }

    private void DrawGridsOn(DrawingHandleScreen handle,
        EntityUid map,
        Matrix3x2 worldToView,
        Color? color,
        EntityUid? skip = null)
    {
        var query = EntManager.EntityQueryEnumerator<MapGridComponent, TransformComponent>();
        while (query.MoveNext(out var uid, out var grid, out var xform))
        {
            if (xform.MapUid != map || uid == map || uid == skip)
                continue;

            var gridToView = _transform.GetWorldMatrix(xform) * worldToView;
            DrawGrid(handle, gridToView, (uid, grid), color ?? _shuttles.GetIFFColor(uid));
        }
    }

    private bool TryGetBelow(EntityUid map, out EntityUid below, out float gap)
    {
        below = default;
        gap = 0f;
        if (!_layers.TryGetGaps(map, _gaps) || _gaps.Count == 0 || _gaps[0].Map == map)
            return false;

        below = _gaps[0].Map;
        gap = MathF.Max(_gaps[0].Gap, 0f);
        return true;
    }
}
