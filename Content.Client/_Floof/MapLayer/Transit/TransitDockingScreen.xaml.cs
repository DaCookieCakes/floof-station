using Content.Shared._Floof.MapLayer;
using Content.Shared._Floof.MapLayer.Transit;
using Content.Shared.Shuttles.BUIStates;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Floof.MapLayer.Transit;

[GenerateTypedNameReferences]
public sealed partial class TransitDockingScreen : BoxContainer
{
    [Dependency] private IEntityManager _entManager = default!;

    public Dictionary<NetEntity, List<DockingPortState>> Docks = new();

    private readonly Dictionary<NetEntity, Button> _ourDockButtons = new();

    public event Action<NetEntity, NetEntity>? DockRequest;
    public event Action<NetEntity>? UndockRequest;
    public event Action? OnLift;
    public event Action? OnLand;
    public event Action? OnDock;

    private EntityUid? _shuttle;

    private bool _landed;

    public TransitDockingScreen()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        LiftButton.OnPressed += _ => (_landed ? OnLift : OnLand)?.Invoke();
        DockButton.OnPressed += _ => OnDock?.Invoke();
        DockingControl.OnViewDock += OnView;
        DockingControl.DockRequest += (entity, netEntity) =>
        {
            DockRequest?.Invoke(entity, netEntity);
        };
        DockingControl.UndockRequest += entity =>
        {
            UndockRequest?.Invoke(entity);
        };
    }

    protected override void Draw(DrawingHandleScreen handle)
    {
        base.Draw(handle);

        var map = _entManager.GetComponentOrNull<TransformComponent>(_shuttle)?.MapUid;
        _landed = _entManager.HasComponent<MapLayerSeabedComponent>(map);
        var moving = _entManager.HasComponent<MapLayerTransitionComponent>(map);

        var text = Loc.GetString(_landed ? "transit-lift" : "transit-land");
        if (LiftButton.Text != text)
            LiftButton.Text = text;

        LiftButton.Disabled = moving;
        DockButton.Disabled = _landed || moving || !_entManager.HasComponent<TransitDockPreviewComponent>(_shuttle);
    }

    private void OnView(NetEntity obj)
    {
        foreach (var (dock, button) in _ourDockButtons)
        {
            button.Pressed = dock == obj;
        }
    }

    public void UpdateState(EntityUid? shuttle, DockingInterfaceState state)
    {
        _shuttle = shuttle;
        DockView.Shuttle = shuttle;
        Docks = state.Docks;
        DockingControl.DockState = state;
        DockingControl.GridEntity = shuttle;
        BuildDocks(shuttle);
    }

    private void BuildDocks(EntityUid? shuttle)
    {
        DockingControl.BuildDocks(shuttle);
        var currentDock = DockingControl.ViewedDock;
        DockPorts.RemoveAllChildren();
        _ourDockButtons.Clear();

        if (shuttle == null ||
            !Docks.TryGetValue(_entManager.GetNetEntity(shuttle.Value), out var shuttleDocks) ||
            shuttleDocks.Count <= 0)
        {
            ViewDock(null);
            return;
        }

        var selected = false;

        foreach (var dock in shuttleDocks)
        {
            var button = new Button()
            {
                Text = dock.Name,
                ToggleMode = true,
                Margin = new Thickness(0f, 3f),
            };

            button.OnMouseEntered += _ =>
            {
                DockingControl.HighlightedDock = dock.Entity;
            };

            button.OnMouseExited += _ =>
            {
                DockingControl.HighlightedDock = null;
            };

            button.Label.Margin = new Thickness(3f);

            if (currentDock == dock.Entity)
            {
                selected = true;
                button.Pressed = true;
            }

            button.OnToggled += args =>
            {
                if (!args.Pressed)
                {
                    ViewDock(null);
                    return;
                }

                foreach (var other in _ourDockButtons.Values)
                {
                    if (other != args.Button)
                        other.Pressed = false;
                }

                ViewDock(dock);
            };

            _ourDockButtons[dock.Entity] = button;
            DockPorts.AddChild(button);
        }

        if (!selected)
            ViewDock(null);
    }

    private void ViewDock(DockingPortState? state)
    {
        DockingControl.SetViewedDock(state);
        DockingControl.Visible = state != null;
        DockView.Visible = state == null;
    }
}
