using System.Diagnostics.CodeAnalysis;
using System.Numerics;
using Content.Client.Kitchen.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using FancyWindow = Content.Client.UserInterface.Controls.FancyWindow;

namespace Content.Client._Floof.Kitchen.UI;

/// <summary>
/// Oven variant of the microwave menu. Shows its contents as a grid of slots (rows of four)
/// instead of a list, one slot per unit of capacity.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class OvenMenu : FancyWindow
{
    [Dependency] private IGameTiming _timing = default!;

    private static readonly Vector2 SlotSize = new(64, 64);

    public event Action<string, int, uint>? OnCookTimeSelected;

    /// <summary>
    /// Raised when a filled slot is clicked, with the entity in that slot.
    /// </summary>
    public event Action<EntityUid>? OnSlotPressed;

    public ButtonGroup CookTimeButtonGroup { get; }
    public bool IsBusy;
    public TimeSpan CurrentCooktimeEnd;

    private readonly StyleBoxFlat _ingredientsStylebox = new() { BackgroundColor = Color.FromHex("#1B1B1E") };
    private readonly List<(OvenSlotButton Button, SpriteView View)> _slots = new();
    private readonly List<EntityUid?> _slotEntities = new();

    public OvenMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        IngredientsPanel.PanelOverride = _ingredientsStylebox;

        CookTimeButtonGroup = new ButtonGroup();
        InstantCookButton.Group = CookTimeButtonGroup;
        InstantCookButton.OnCookTimeSelected += (name, cookTime) => OnCookTimeSelected?.Invoke(name, 0, cookTime);

        for (var i = 1; i <= 6; i++)
        {
            var index = i;
            var newButton = new MicrowaveCookTimeButton
            {
                CookTime = (uint) (i * 5),
                Group = CookTimeButtonGroup,
            };

            newButton.OnCookTimeSelected += (name, cookTime) => OnCookTimeSelected?.Invoke(name, index, cookTime);
            CookTimeButtonVbox.AddChild(newButton);
        }
    }

    /// <summary>
    /// Make sure the grid has exactly <paramref name="count"/> slots.
    /// </summary>
    public void EnsureSlotCount(int count)
    {
        count = Math.Max(count, 1);
        if (_slots.Count == count)
            return;

        SlotGrid.RemoveAllChildren();
        _slots.Clear();
        _slotEntities.Clear();

        for (var i = 0; i < count; i++)
        {
            var index = i;
            var button = new OvenSlotButton
            {
                SetSize = SlotSize,
                Disabled = true,
            };

            var view = new SpriteView
            {
                SetSize = SlotSize,
                Scale = new Vector2(2,2),
                Stretch = SpriteView.StretchMode.Fit,
                OverrideDirection = Direction.South,
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center,
            };

            button.AddChild(view);
            button.OnPressed += _ =>
            {
                if (_slotEntities[index] is { } ent)
                    OnSlotPressed?.Invoke(ent);
            };

            SlotGrid.AddChild(button);
            _slots.Add((button, view));
            _slotEntities.Add(null);
        }
    }

    /// <summary>
    /// Put an entity (or nothing) into the given slot.
    /// </summary>
    public void SetSlot(int index, EntityUid? entity, string? name)
    {
        if (index < 0 || index >= _slots.Count)
            return;

        var (button, view) = _slots[index];
        _slotEntities[index] = entity;
        view.SetEntity(entity);
        button.Disabled = entity == null;
        button.ToolTip = name;
    }

    public int SlotCount => _slots.Count;

    /// <summary>
    /// Set the visibility of the "busy overlay panel", blocking interaction while the oven is running.
    /// </summary>
    public void ToggleBusyDisableOverlayPanel(bool shouldDisable)
    {
        DisableCookingPanelOverlay.Visible = shouldDisable;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!IsBusy)
            return;

        var remaining = CurrentCooktimeEnd - _timing.CurTime;
        if (remaining > TimeSpan.Zero)
        {
            CookTimeInfoLabel.Text = Loc.GetString("microwave-bound-user-interface-cook-time-label",
                ("time", Math.Ceiling(remaining.TotalSeconds)));
        }
    }

    /// <summary>
    /// Set the "oven light" color of the slot panel.
    /// </summary>
    public void SetIngredientPanelLight(bool value)
    {
        _ingredientsStylebox.BackgroundColor = value
            ? Color.DarkOrange.WithAlpha(0.6f)
            : Color.FromHex("#1B1B1E");
    }

    /// <summary>
    /// Attempt to get the cook time button at the given index.
    /// </summary>
    public bool TryGetCookTimeButton(int index, [NotNullWhen(true)] out Button? button)
    {
        button = null;

        if (index == 0)
            button = InstantCookButton;
        else if (index <= CookTimeButtonVbox.ChildCount && CookTimeButtonVbox.GetChild(index - 1) is Button timeButton)
            button = timeButton;

        return button != null;
    }
}

/// <summary>
///     A flat, square slot button. Swaps a plain <see cref="StyleBoxFlat"/> per draw mode
///     instead of using the default beveled button style.
/// </summary>
public sealed class OvenSlotButton : ContainerButton
{
    private static readonly StyleBoxFlat NormalBox = new() { BackgroundColor = Color.FromHex("#2B2B31") };
    private static readonly StyleBoxFlat HoverBox = new() { BackgroundColor = Color.FromHex("#3C3C45") };
    private static readonly StyleBoxFlat PressedBox = new() { BackgroundColor = Color.FromHex("#50505C") };
    private static readonly StyleBoxFlat DisabledBox = new() { BackgroundColor = Color.FromHex("#222226") };

    public OvenSlotButton()
    {
        StyleBoxOverride = NormalBox;
    }

    protected override void DrawModeChanged()
    {
        StyleBoxOverride = DrawMode switch
        {
            DrawModeEnum.Hover => HoverBox,
            DrawModeEnum.Pressed => PressedBox,
            DrawModeEnum.Disabled => DisabledBox,
            _ => NormalBox,
        };

        base.DrawModeChanged();
    }
}
